const assert = require('node:assert/strict');
const { fixture, png } = require('./client-jobs.test.cjs');
const { NextRequest } = require('next/server');
(async () => {
  const f = await fixture();
  const originalEnv = { ...process.env };
  const get = async (token) => {
    const r = await f.pub.GET(f.req('/api/client-upload/' + token), { params: { token } });
    return { status: r.status, ...await r.json() };
  };
  try {
    const initial = await (await f.owner.GET(f.req('/', undefined, 'basic'))).json();
    assert.equal(initial.portal.active, false);
    const token = initial.portal.url.split('/').at(-1);
    const enable = async () => {
      const response = await f.owner.POST(f.req('/', { action:'save', profileId:initial.portal.id,
        name:initial.portal.name, settings:{...initial.portal.settings,shopName:'Test shop'} }, 'basic'));
      assert.equal(response.status,200);
      return (await response.json()).portal.url.split('/').at(-1);
    };
    assert.match(token, /^[A-Za-z0-9_-]{43}$/);
    assert.equal((await get(token)).code, 'portal_disabled');
    delete process.env.RESEND_API_KEY;
    delete process.env.CLIENT_JOBS_EMAIL_FROM; delete process.env.CRON_SECRET;
    const setup = await (await f.owner.GET(f.req('/', undefined, 'basic'))).json();
    assert.deepEqual(setup.setupIssues, []);
    assert.equal(setup.emailConfigured, false);
    for (const key of ['RESEND_API_KEY', 'CLIENT_JOBS_EMAIL_FROM', 'CRON_SECRET'])
      assert(setup.serviceWarnings.some(x => x.includes(key)));
    assert.equal((await get(token)).message, 'This upload portal is currently disabled.');
    const enabled = await enable();
    assert.equal(enabled, token, 'enable persists and retains generated token');
    const publicProfile = await get(token);
    assert.equal(publicProfile.status, 200);
    assert.equal(publicProfile.shopName, 'Test shop');
    assert.equal(publicProfile.profileName, initial.portal.name);
    assert.equal(publicProfile.machine, 'dtf');
    assert.deepEqual(publicProfile.limits, { maxFileMiB:50, maxTotalMiB:150, maxFileBytes:52428800, maxTotalBytes:157286400, maxFiles:10, maxPieces:500 });
    const active = await (await f.owner.GET(f.req('/', undefined, 'basic'))).json();
    assert.equal(active.portal.active, true);
    assert.equal(active.portal.url, 'https://shop.test/client-upload/' + token);
    assert.equal((await f.owner.POST(f.req('/', { action:'enable',profileId:initial.portal.id }))).status,401);
    assert.equal((await f.maintenance.GET(f.req('/maintenance'))).status,401,'missing cron secret never opens maintenance');
    const noEmailDraft = await f.call('create',token);
    assert.equal(noEmailDraft.status,200);
    const uploaded = await f.call('upload',token,noEmailDraft.submission,png());
    assert.equal(uploaded.status,200);
    const preview = await f.call('preview',token,noEmailDraft.submission,{
      quantities:uploaded.job.assets.map(a=>({id:a.id,qty:10,widthIn:5,heightIn:5}))
    });
    assert.equal(preview.status,200,'email and cron are not preview dependencies');
    const beforeConfirm=await f.one('select * from client_jobs where id=$1',[noEmailDraft.job.id]);
    const confirm = await f.call('confirm',token,noEmailDraft.submission,{revision:preview.job.revision});
    assert.equal(confirm.status,503);
    assert.equal(confirm.code,'portal_email_not_configured');
    assert.match(confirm.message,/email delivery is not configured/);
    assert(!confirm.message.includes('could not connect'));
    const savedDraft=await f.one('select * from client_jobs where id=$1',[noEmailDraft.job.id]);
    assert.equal(savedDraft.confirmed_at,null);
    assert.equal(savedDraft.revision,preview.job.revision);
    assert.deepEqual(savedDraft,beforeConfirm,'failed confirmation preserves all draft data, preview and sizes');
    assert.equal(f.emails.length,0);
    process.env.CLIENT_JOBS_EMAIL_FROM=originalEnv.CLIENT_JOBS_EMAIL_FROM;
    process.env.RESEND_API_KEY=originalEnv.RESEND_API_KEY;
    const confirmed=await f.call('confirm',token,noEmailDraft.submission,{revision:preview.job.revision});
    assert.equal(confirmed.status,200,'email confirmation works independently of cron configuration');
    assert.equal(new Date(confirmed.job.expires_at)-new Date(confirmed.job.confirmed_at),86400000);
    delete process.env.RESEND_API_KEY;
    const replay=await f.call('confirm',token,noEmailDraft.submission,{revision:preview.job.revision});
    assert.equal(replay.status,200,'already confirmed jobs remain idempotent when email configuration changes');
    assert.equal(replay.job.expires_at,confirmed.job.expires_at);
    process.env.RESEND_API_KEY=originalEnv.RESEND_API_KEY;
    const rows=async()=>({
      jobs:await f.q('select * from client_jobs order by id'),
      profiles:await f.q('select * from client_upload_profiles order by id')
    });
    const beforeMigration=await rows();
    const migration=require('node:fs').readFileSync('supabase-client-upload-limits-v1.sql','utf8');
    await f.db.exec(migration); await f.db.exec(migration);
    assert.deepEqual(await rows(),beforeMigration,'additive migration reruns preserve existing jobs/profiles exactly');
    await f.q("update storage.buckets set file_size_limit=67108864 where id='client-job-sources'");
    await f.db.exec(migration);
    assert.equal(Number((await f.one("select file_size_limit from storage.buckets where id='client-job-sources'")).file_size_limit),67108864,'migration never lowers a larger existing storage limit');
    await f.q("update client_jobs set expires_at=clock_timestamp()-interval '1 second' where id=$1",[confirmed.job.id]);
    assert.equal((await f.owner.GET(f.req(`/?id=${confirmed.job.id}`,undefined,'basic'))).status,410,'24-hour access expiry is independent of cron configuration');
    process.env.CRON_SECRET=originalEnv.CRON_SECRET;
    delete process.env.RESEND_API_KEY;
    const cleaned=await f.maintenance.GET(f.req('/maintenance',undefined,null,{Authorization:`Bearer ${process.env.CRON_SECRET}`}));
    assert.equal(cleaned.status,200,'authorized physical cleanup does not depend on email delivery');
    const cleanedBody=await cleaned.json();
    assert.equal(cleanedBody.emailConfigured,false);
    assert.equal(cleanedBody.notified,0);
    assert.equal(cleanedBody.purged,1);
    assert.equal((await f.maintenance.GET(f.req('/maintenance',undefined,null,{Authorization:'Bearer incorrect'}))).status,401);
    process.env.RESEND_API_KEY=originalEnv.RESEND_API_KEY;
    assert.equal((await get('x'.repeat(43))).code, 'portal_not_found');
    assert.equal((await get('invalid')).code, 'portal_not_found');
    const draft = await f.call('create', token);
    await f.q("update client_jobs set expires_at=clock_timestamp()-interval '1 second' where id=$1", [draft.job.id]);
    assert.equal((await f.call('preview', token, draft.submission)).code, 'submission_expired');
    const rotated = await (await f.owner.POST(f.req('/', { action: 'rotate', profileId:initial.portal.id }, 'basic'))).json();
    const replacement = rotated.portal.url.split('/').at(-1);
    assert.notEqual(replacement, token);
    assert.equal((await get(token)).code, 'portal_not_found');
    assert.equal((await get(replacement)).status, 200);
    delete process.env.RESEND_API_KEY;
    assert.equal((await get(replacement)).status, 200,'missing email never masquerades as an invalid/unavailable link');
    process.env.RESEND_API_KEY = originalEnv.RESEND_API_KEY;
    await f.owner.POST(f.req('/', { action: 'disable', profileId:initial.portal.id }, 'basic'));
    assert.equal((await get(replacement)).code, 'portal_disabled');
    assert.equal((await enable()), replacement, 're-enable retains replacement');
    const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
    delete process.env.SUPABASE_SERVICE_ROLE_KEY;
    assert.equal((await get(replacement)).code, 'portal_supabase_not_configured');
    process.env.SUPABASE_SERVICE_ROLE_KEY = serviceKey;
    // A deployment running the earlier SQL must ask for its schema update, not a new customer link.
    const oldError = Object.assign(Error('Upload link unavailable. Ask the shop for a new link.'), { data: { code: 'P0002' } });
    assert.equal((await f.lib.errorReply(oldError).json()).code, 'portal_setup_required');
    const deniedRpc = Object.assign(Error('permission denied for function ssb_client_jobs'), { data: { code: '42501' } });
    assert.equal(f.lib.errorReply(deniedRpc).status, 503, 'broken server grants are configuration failures, not invalid links');
    await f.q('alter function ssb_client_jobs(text,uuid,text,uuid,jsonb) rename to temporarily_missing_client_jobs');
    const missing = await get(replacement);
    assert.equal(missing.status, 503);
    assert.equal(missing.code, 'portal_setup_required');
    assert(!missing.message.includes('Ask the shop for a new link'));
    await f.q('alter function temporarily_missing_client_jobs(text,uuid,text,uuid,jsonb) rename to ssb_client_jobs');
    process.env.NODE_ENV = 'production';
    delete process.env.VERCEL;
    process.env.SMART_SHEET_SITE_URL = 'https://smart-sheet-builder.vercel.app';
    assert.equal(f.lib.publicOrigin(new NextRequest('http://localhost:3000/api/client-jobs')), 'http://localhost:3000');
    process.env.VERCEL = '1';
    assert.equal(f.lib.publicOrigin(new NextRequest('https://smart-sheet-builder.vercel.app/api/client-jobs')), 'https://smart-sheet-builder.vercel.app');
    process.env.SMART_SHEET_SITE_URL = 'http://localhost:3000';
    assert.throws(() => f.lib.publicOrigin(f.req('/')));
    const badOrigin=await f.owner.POST(f.req('/',{action:'enable',profileId:initial.portal.id},'basic'));
    assert.equal(badOrigin.status,503);
    const badOriginBody=await badOrigin.json();
    assert.equal(badOriginBody.code,'portal_configuration_missing');
    assert.match(badOriginBody.message,/SMART_SHEET_SITE_URL/);
    assert(!badOriginBody.message.includes('could not connect'));
    assert.equal((await get(replacement)).code,'portal_origin_not_configured');
    process.env.SMART_SHEET_SITE_URL = 'https://user:password@example.test';
    assert.throws(() => f.lib.publicOrigin(f.req('/')));
    delete process.env.SMART_SHEET_SITE_URL;
    process.env.VERCEL_ENV = 'production';
    process.env.VERCEL_PROJECT_PRODUCTION_URL = 'smart-sheet-builder.vercel.app';
    assert.equal(f.lib.publicOrigin(new NextRequest('https://attacker.test/')), 'https://smart-sheet-builder.vercel.app');
    console.log('PASS: save/enable and public upload/preview without Resend/cron, truthful confirmation error and safe retry, exact expiry without cron, protected maintenance, non-destructive migration reruns, opaque link lifecycle, schema diagnostics, localhost/production origins and Host-injection rejection.');
  } finally {
    for (const key of Object.keys(process.env)) if (!(key in originalEnv)) delete process.env[key];
    Object.assign(process.env, originalEnv);
    await f.close();
  }
})().catch(e => { console.error(e); process.exitCode = 1; });
